using ((select auth.uid()) = patient_id);

-- Enable Postgres Changes for the two tables used by the live dashboard.
-- This block is safe to run more than once.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'sensor_readings'
  ) then
    alter publication supabase_realtime add table public.sensor_readings;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'exercise_sessions'
  ) then
    alter publication supabase_realtime add table public.exercise_sessions;
  end if;
end;
$$;
