drop policy if exists "device_update_own" on public.devices;
create policy "device_update_own" on public.devices for update to authenticated
using ((select auth.uid()) = patient_id) with check ((select auth.uid()) = patient_id);

drop policy if exists "session_select_own" on public.exercise_sessions;
create policy "session_select_own" on public.exercise_sessions for select to authenticated
using ((select auth.uid()) = patient_id);

drop policy if exists "session_insert_own" on public.exercise_sessions;
create policy "session_insert_own" on public.exercise_sessions for insert to authenticated
with check ((select auth.uid()) = patient_id);

drop policy if exists "session_update_own" on public.exercise_sessions;
create policy "session_update_own" on public.exercise_sessions for update to authenticated
using ((select auth.uid()) = patient_id) with check ((select auth.uid()) = patient_id);

